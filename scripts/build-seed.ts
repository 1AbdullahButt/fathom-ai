// Build the static seeded meetings that the app reads (PLAN.md Architecture: seed/meetings/*.json).
// Inputs: seed/transcripts/<slug>.json (AssemblyAI, sentence segments) + seed/speakers.json,
// and the two SPEC fixtures (tests/fixtures/meeting{1,2}.json) as transcript-only meetings.
// Outputs: seed/meetings/<id>.json, seed/index.ts (static imports, so `next build` bundles them),
// and public/media/<slug>.mp3 (copied from seed/media).
// Summaries, action items and chapters stay empty here; later scripts (P0-6 / P2) fill them.
// Existing filled fields are preserved on re-run so this script never wipes generated content.
// Usage: npx tsx scripts/build-seed.ts
import fs from "node:fs";
import path from "node:path";
import type { Meeting, Segment } from "../lib/types";
import type { SeedMeetingFile } from "../lib/seed";

const ROOT = path.resolve(__dirname, "..");
const SEED = path.join(ROOT, "seed");
const OUT = path.join(SEED, "meetings");
const MEDIA_OUT = path.join(ROOT, "public", "media");

interface RawSegment { speaker: string; start_s: number; end_s: number; text: string }
interface RawTranscript { slug: string; duration_s: number; segments: RawSegment[] }
interface SpeakerEntry { title: string; date: string; speakers: Record<string, string> }

const round = (n: number) => Math.round(n * 1000) / 1000;

function readJson<T>(p: string): T {
  return JSON.parse(fs.readFileSync(p, "utf8")) as T;
}

function keepGenerated(file: string, fresh: SeedMeetingFile): SeedMeetingFile {
  if (!fs.existsSync(file)) return fresh;
  const old = readJson<SeedMeetingFile>(file);
  return {
    ...fresh,
    chapters: old.chapters ?? [],
    summaries: old.summaries ?? {},
    action_items: old.action_items ?? [],
  };
}

function fromTranscript(slug: string, info: SpeakerEntry): SeedMeetingFile {
  const raw = readJson<RawTranscript>(path.join(SEED, "transcripts", `${slug}.json`));
  const letters = [...new Set(raw.segments.map((s) => s.speaker))].sort();
  for (const l of letters) {
    if (!info.speakers[l]) throw new Error(`${slug}: speaker ${l} has no name in speakers.json`);
  }
  const meeting: Meeting = {
    id: slug,
    title: info.title,
    date: info.date,
    duration_s: Math.round(raw.duration_s),
    media_url: `/media/${slug}.mp3`,
    speakers: letters.map((l) => ({ id: `spk-${l}`, name: info.speakers[l] })),
    status: "ready",
    source: "seed",
  };
  const segments: Segment[] = raw.segments.map((s, i) => ({
    id: `${slug}-s${i + 1}`,
    meeting_id: slug,
    start_s: round(s.start_s),
    end_s: round(s.end_s),
    speaker_id: `spk-${s.speaker}`,
    text: s.text,
  }));
  return { meeting, segments, chapters: [], summaries: {}, action_items: [] };
}

function fromFixture(file: string): SeedMeetingFile {
  const f = readJson<{ meeting: Meeting; segments: Segment[] }>(file);
  return { meeting: { ...f.meeting, media_url: null, source: "seed", status: "ready" }, segments: f.segments, chapters: [], summaries: {}, action_items: [] };
}

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  fs.mkdirSync(MEDIA_OUT, { recursive: true });

  const speakers = readJson<Record<string, SpeakerEntry | string>>(path.join(SEED, "speakers.json"));
  const built: SeedMeetingFile[] = [];
  for (const [slug, info] of Object.entries(speakers)) {
    if (slug.startsWith("_") || typeof info === "string") continue;
    built.push(fromTranscript(slug, info));
    const mp3 = path.join(SEED, "media", `${slug}.mp3`);
    if (!fs.existsSync(mp3)) throw new Error(`missing ${mp3}`);
    fs.copyFileSync(mp3, path.join(MEDIA_OUT, `${slug}.mp3`));
  }
  for (const name of ["meeting1.json", "meeting2.json"]) {
    built.push(fromFixture(path.join(ROOT, "tests", "fixtures", name)));
  }

  const ids: string[] = [];
  for (const m of built) {
    const file = path.join(OUT, `${m.meeting.id}.json`);
    fs.writeFileSync(file, JSON.stringify(keepGenerated(file, m), null, 2) + "\n");
    ids.push(m.meeting.id);
    console.log(`${m.meeting.id}: ${m.segments.length} segments, ${m.meeting.speakers.length} speakers`);
  }

  ids.sort();
  const ident = (id: string) => "m_" + id.replace(/[^a-zA-Z0-9]/g, "_");
  const index = [
    "// GENERATED by scripts/build-seed.ts. Do not edit by hand.",
    "// Static imports so the seeded meetings are bundled by `next build` (no fs reads at runtime).",
    'import type { SeedMeetingFile } from "../lib/seed";',
    ...ids.map((id) => `import ${ident(id)} from "./meetings/${id}.json";`),
    "",
    "export const seedFiles = [",
    ...ids.map((id) => `  ${ident(id)},`),
    "] as unknown as SeedMeetingFile[];",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(SEED, "index.ts"), index);
  console.log(`wrote ${ids.length} meetings + seed/index.ts`);
}

main();
